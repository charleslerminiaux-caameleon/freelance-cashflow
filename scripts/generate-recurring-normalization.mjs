import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
// Regenerate only deliberately: changing Unicode versions may change persisted series identities.
const path = fileURLToPath(new URL('../supabase/migrations/202609110002_recurring_detection_functions.sql', import.meta.url));
function ranges(pattern) {
  const values = [];
  let start;
  for (let code = 1; code <= 0x110000; code++) {
    const matches = code <= 0x10ffff && pattern.test(String.fromCodePoint(code));
    if (matches && start === undefined) start = code;
    if (!matches && start !== undefined) {
      const end = code - 1;
      const escape = n => `\\${n <= 0xffff ? 'u' : 'U'}${n.toString(16).padStart(n <= 0xffff ? 4 : 8, '0')}`;
      values.push(escape(start) + (end === start ? '' : `-${escape(end)}`));
      start = undefined;
    }
  }
  return values.join('');
}
if (process.versions.unicode !== '17.0') throw new Error('Review persisted identity compatibility before changing Unicode version');
const escaped = text => [...text].map(c => `\\${c.codePointAt(0) <= 0xffff ? 'u' : 'U'}${c.codePointAt(0).toString(16).padStart(c.codePointAt(0) <= 0xffff ? 4 : 8, '0')}`).join('');
let upper = '', lower = '';
for (let n = 1; n <= 0x10ffff; n++) {
  const c = String.fromCodePoint(n), down = c.toLowerCase();
  // Dotted I has already decomposed; capital sigma needs its contextual rule first.
  if (c !== down && n !== 0x130 && n !== 0x3a3) { upper += c; lower += down; }
}
upper += 'Σ'; lower += 'σ';
// Exhaustive comparison with PostgreSQL 17.6 found these newer canonical decompositions.
// Removing marks makes canonical combining order immaterial. No compatibility expansions.
let input = 'p_label';
for (const code of [0x105c9, 0x105e4, 0x11383, 0x11385, 0x1138e, 0x11391, 0x16d68, 0x16d69, 0x16d6a]) {
  const c = String.fromCodePoint(code);
  input = `replace(${input},E'${escaped(c)}',E'${escaped(c.normalize('NFD'))}')`;
}
const section = `-- BEGIN GENERATED NORMALIZATION (Node Unicode ${process.versions.unicode})
-- Canonical decomposition, all Mark removal, locale-independent lowercase, then L/N only.
-- Generated by scripts/generate-recurring-normalization.mjs; never use unaccent here.
create or replace function public.normalize_recurring_label(p_label text) returns text
language sql immutable strict parallel safe set search_path = '' as $normalize$
  with stripped as (
    select regexp_replace(normalize(${input},NFD), '[${ranges(/\p{M}/u)}]+', '', 'g') value
  ), contextual as (
    select regexp_replace(value, '(?<=[${ranges(/\p{Cased}/u)}][${ranges(/\p{Case_Ignorable}/u)}]*)Σ(?![${ranges(/\p{Case_Ignorable}/u)}]*[${ranges(/\p{Cased}/u)}])', 'ς', 'g') value from stripped
  )
  select btrim(regexp_replace(translate(value,'${upper}','${lower}'), '[^${ranges(/[\p{L}\p{N}]/u)}]+', ' ', 'g')) from contextual;
$normalize$;
-- END GENERATED NORMALIZATION`;

const existing = await readFile(path, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
const updated = existing.includes('-- BEGIN GENERATED NORMALIZATION')
  ? existing.replace(/-- BEGIN GENERATED NORMALIZATION[\s\S]*?-- END GENERATED NORMALIZATION/, () => section)
  : section + '\n\n' + existing;
await writeFile(path, updated);
console.log(`Generated Unicode ${process.versions.unicode} normalization (${Buffer.byteLength(section)} bytes).`);
